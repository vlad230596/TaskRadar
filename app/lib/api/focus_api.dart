import '../models/focus_task.dart';
import 'api_client.dart';

/// Набор «в работе»: три роута, которыми живёт режим работы (F13).
///
/// ## Почему набор серверный
///
/// Список id в памяти телефона был бы дешевле во всём, кроме главного: набор
/// собирают за столом, где пятнадцать проектов помещаются на один экран, а
/// отрабатывают с телефона в очереди. Набор, который знает только собравшее его
/// устройство, — это набор, которого не видит устройство, которому он нужен.
/// Длинный вариант этого рассуждения — в `backend/src/routes/focus.ts`.
///
/// ## Что важно знать вызывающему
///
/// **Порядок набора задаёт сервер** — `focusedAt` по возрастанию. Клиент его не
/// пересчитывает и не сортирует, ровно как и `position` у обычной задачи.
///
/// **Оба write-роута идемпотентны, и это решение, а не случайность.** Повторный
/// `POST` на задачу, которая уже в наборе, оставляет ей прежний `focusedAt` и
/// ничего не пишет в журнал: пере-штамповка сдвинула бы её в конец набора, то
/// есть двойной тап на телефоне молча переставил бы работу, которая уже идёт.
/// `DELETE` на задачу, которой в наборе нет, — тоже не ошибка. Для клиента это
/// значит, что повтор после неясного сбоя безопасен, а 409 «уже в наборе»
/// обрабатывать не нужно: его не бывает.
///
/// **Предела в пять здесь нет.** Пять — это то, что помещается на экран и в
/// голову (`design/reference/Pick.html` рисует пять слотов); сервер про это не
/// знает и знать не обязан. Правило живёт на экране сбора — см.
/// `kFocusSlots` в `providers/focus_providers.dart`.
class FocusApi {
  const FocusApi(this._client);

  final ApiClient _client;

  /// `GET /focus` — набор целиком, в порядке, в котором его собирали.
  ///
  /// Каждая строка несёт свой проект (id и имя), так что экрану работы не нужно
  /// join-иться с доской, которая вполне может быть вчерашней. Архивные проекты
  /// сервер отсюда **не** вычищает: задача, которую человек сознательно взял в
  /// работу, не должна исчезать с единственного экрана, на который он смотрит,
  /// из-за того, что проект вокруг неё прибрали.
  Future<List<FocusTask>> fetchFocus() async {
    final json = await _client.get<List<dynamic>>('/focus');
    return List<FocusTask>.unmodifiable(
      json.map((dynamic e) => FocusTask.fromJson(e as Map<String, dynamic>)),
    );
  }

  /// `POST /tasks/:id/focus` — взять задачу в работу.
  ///
  /// Ответ — сырая строка задачи (без `project`, без `isCurrent`), и он здесь
  /// не нужен: новый порядок набора и имя проекта всё равно приходят следующим
  /// `GET /focus`, а строить из этого ответа [FocusTask] значило бы додумывать
  /// половину полей. Поэтому `dynamic` и `void` — та же типизация и по той же
  /// причине, что у `ProjectApi.deleteTask`.
  Future<void> addToFocus(String taskId) =>
      _client.post<dynamic>('/tasks/$taskId/focus');

  /// `DELETE /tasks/:id/focus` — убрать из набора.
  ///
  /// Не единственный выход из набора: закрытая задача покидает его сама, из
  /// `PATCH /tasks/:id` (см. `backend/src/domain/taskEvents.ts`). Поэтому после
  /// «сделано» набор перечитывается, а не правится по месту.
  Future<void> removeFromFocus(String taskId) =>
      _client.delete<dynamic>('/tasks/$taskId/focus');
}
